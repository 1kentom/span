// @vitest-environment jsdom
import { afterEach, expect, it, vi } from "vitest";
import { render } from "solid-js/web";
import { createSignal } from "solid-js";
import type { GitContext } from "../../bindings";
import type { GitWorkbench } from "../../stores/git";
const transport = vi.hoisted(() => ({ gitHistoryTools: vi.fn(), gitReflogPage: vi.fn(), gitRevisionContent: vi.fn(), gitRevisionDiff: vi.fn(), gitLineHistory: vi.fn() }));
vi.mock("../../bindings", () => ({ commands: transport }));
import { GitHistoryTools } from "./GitHistoryTools";
let dispose: (() => void) | undefined;
afterEach(() => { dispose?.(); document.body.replaceChildren(); vi.clearAllMocks(); });
it("submits repository filters, reads revisions and traces the exact active-file line range", async () => {
  const context: GitContext = { enabled: true, workspaceRoot: "/work", unavailableReason: null, repository: { id: "r", root: "/work", workspacePrefix: "", head: "h", branch: "main", detached: false, unborn: false } };
  transport.gitHistoryTools.mockResolvedValue({ heads: ["h"], refs: [], commits: [], nextSkip: null });
  transport.gitRevisionContent.mockResolvedValue({ revision: "resolved", path: "file.ts", text: "historical text", binary: false, truncated: false });
  transport.gitLineHistory.mockResolvedValue({ repositoryId: "r", anchor: "resolved", commits: [], nextSkip: null });
  const host = document.createElement("div"); document.body.append(host);
  const git = { context: () => context, openDiff: vi.fn() } as unknown as GitWorkbench;
  dispose = render(() => <GitHistoryTools git={git} path="file.ts" />, host);
  const input = (label: string, value: string) => { const node = [...host.querySelectorAll("label")].find(node => node.textContent === label)!.querySelector("input")!; node.value = value; node.dispatchEvent(new Event("input", { bubbles: true })); };
  const submit = (text: string) => { const button = [...host.querySelectorAll("button")].find(node => node.textContent === text)!; button.closest("form")!.dispatchEvent(new Event("submit", { bubbles: true, cancelable: true })); };
  await vi.waitFor(() => expect(transport.gitHistoryTools).toHaveBeenCalledTimes(1));
  input("Author", "Ada"); input("Message", "fix"); submit("Search history");
  await vi.waitFor(() => expect(transport.gitHistoryTools.mock.calls[1][1]).toMatchObject({ author: "Ada", message: "fix", path: "file.ts", heads: [] }));
  input("Revision", "release"); submit("Read revision file");
  await vi.waitFor(() => expect(host.querySelector('[aria-label="Read-only revision content"]')?.textContent).toBe("historical text"));
  expect(transport.gitRevisionContent).toHaveBeenCalledWith(context, "release", "file.ts");
  input("Start line", "3"); input("End line", "8"); submit("Trace lines");
  await vi.waitFor(() => expect(transport.gitLineHistory).toHaveBeenCalledWith(context, "release", "file.ts", 3, 8, 0, 50));
});

it("keeps filtered results across context polls and resets controls consistently for another repository", async () => {
  const original: GitContext = { enabled: true, workspaceRoot: "/work", unavailableReason: null, repository: { id: "r", root: "/work", workspacePrefix: "", head: "h", branch: "main", detached: false, unborn: false } };
  const [context, setContext] = createSignal(original);
  const commit = { id: "h", parents: [], author: "Ada", authorEmail: "ada@test", timestamp: 1, subject: "Filtered result", body: "" };
  transport.gitHistoryTools.mockResolvedValue({ heads: ["h"], refs: [], commits: [], nextSkip: null });
  transport.gitReflogPage.mockResolvedValue({ entries: [], nextSkip: null });
  const host = document.createElement("div"); document.body.append(host);
  const git = { context, openDiff: vi.fn() } as unknown as GitWorkbench;
  dispose = render(() => <GitHistoryTools git={git} path={context().workspaceRoot === "/work" ? "file.ts" : "other.ts"} />, host);
  const input = (label: string) => [...host.querySelectorAll("label")].find(node => node.textContent === label)!.querySelector("input")!;
  await vi.waitFor(() => expect(transport.gitHistoryTools).toHaveBeenCalledTimes(1));
  expect(transport.gitHistoryTools.mock.calls[0][1].path).toBe("file.ts");
  input("Author").value = "Ada"; input("Author").dispatchEvent(new Event("input", { bubbles: true }));
  input("Message").value = "fix"; input("Message").dispatchEvent(new Event("input", { bubbles: true }));
  transport.gitHistoryTools.mockResolvedValueOnce({ heads: ["h"], refs: [], commits: [commit], nextSkip: null });
  host.querySelector("form")!.dispatchEvent(new Event("submit", { bubbles: true, cancelable: true }));
  await vi.waitFor(() => expect(host.textContent).toContain("Filtered result"));
  setContext({ ...original, repository: { ...original.repository!, head: "updated" } });
  await Promise.resolve();
  expect(transport.gitHistoryTools).toHaveBeenCalledTimes(2);
  expect(input("Author").value).toBe("Ada"); expect(input("Message").value).toBe("fix");
  expect(host.textContent).toContain("Filtered result");
  [...host.querySelectorAll("button")].find(button => button.textContent === "Show HEAD reflog")!.click();
  transport.gitHistoryTools.mockResolvedValueOnce({ heads: ["other"], refs: [], commits: [{ ...commit, subject: "Other repository result" }], nextSkip: null });
  setContext({ ...original, workspaceRoot: "/other", repository: { ...original.repository!, root: "/other" } });
  await vi.waitFor(() => expect(transport.gitHistoryTools).toHaveBeenCalledTimes(3));
  expect(transport.gitHistoryTools.mock.calls[2][1]).toMatchObject({ heads: [], author: null, message: null, path: "other.ts" });
  expect(input("Author").value).toBe(""); expect(input("Message").value).toBe(""); expect(input("Repository path").value).toBe("other.ts");
  await vi.waitFor(() => expect(host.textContent).toContain("Other repository result"));
  expect(host.textContent).not.toContain("Filtered result");
});
